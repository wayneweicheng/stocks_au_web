const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const React = require('react');
const { renderToStaticMarkup } = require('react-dom/server');
require.extensions['.ts'] = require.extensions['.tsx'] = (module, filename) => module._compile(ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.ReactJSX, esModuleInterop: true, target: ts.ScriptTarget.ES2022 } }).outputText, filename);
const { sanitizeMarkdownSource, sanitizeRenderedMarkdown, sandboxedReportDocument } = require('../src/app/components/reportContentSafety.ts');
const MarkdownRenderer = require('../src/app/components/MarkdownRenderer.tsx').default;
const payload = '<img src="x" onerror="alert(localStorage.auth)"><script>alert(1)</script><a href="javascript:alert(1)" onclick="alert(2)">bad</a><div class="fixed inset-0" style="position:fixed">Injected</div>';
const result = renderToStaticMarkup(React.createElement(MarkdownRenderer, { content: '# Report\n\n**Important**\n\n' + payload + '\n\n| Key | Value |\n|---|---|\n| A | 42 |' }));
assert.match(result, /<h1 class="text-xl/);
assert.match(result, /<strong class="font-semibold/);
assert.match(result, /<table class="min-w-full/);
assert.match(result, /Injected/);
for (const dangerous of ['onerror', 'onclick', 'javascript:', 'localStorage', '<script', 'style=', 'class="fixed']) assert.ok(!result.includes(dangerous), dangerous);
assert.match(sanitizeMarkdownSource('<a href="https://example.com">Safe</a>'), /href="https:\/\/example\.com"/);
assert.match(sanitizeMarkdownSource('<a href="https://example.com" target="_blank">Safe</a>'), /rel="noopener noreferrer"/);
assert.doesNotMatch(sanitizeRenderedMarkdown('<a href="java&#x73;cript:alert(1)">bad</a>'), /href=/);
const html = '<h1>Chart</h1><script>parent.localStorage.clear()</script>"</iframe><script>alert(2)</script><iframe src="https://evil.test">';
const wrapped = sandboxedReportDocument(html);
assert.equal((wrapped.match(/<iframe\b/g) || []).length, 1);
assert.doesNotMatch(wrapped, /<script\b/);
assert.doesNotMatch(wrapped, /<\/iframe><script/);
assert.match(wrapped, /sandbox="allow-scripts"/);
assert.doesNotMatch(wrapped, /allow-same-origin|allow-top-navigation|allow-forms|allow-popups|allow-modals/);
assert.match(wrapped, /&lt;script&gt;/);
const skill = fs.readFileSync(path.join(__dirname, '../src/app/components/SkillReportPage.tsx'), 'utf8');
const signals = fs.readFileSync(path.join(__dirname, '../src/app/trading-signal-reports/page.tsx'), 'utf8');
assert.match(skill, /new Blob\(\[sandboxedReportDocument\(detail\.content\)\]/);
assert.match(skill, /sandbox="allow-scripts"/);
assert.match(signals, /new Blob\(\[sandboxedReportDocument\(html\)\]/);
console.log('Report Markdown sanitized and full HTML opened only in an isolated sandbox');
